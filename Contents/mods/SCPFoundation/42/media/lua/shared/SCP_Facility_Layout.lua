--[[
    SCP site: where it is and what is where.

    The plan itself is in SCP_Facility_Data.lua (generated by
    tools/make_site_layout.py). It is laid out like SCP - Containment Breach:
    one underground level with three zones in a row,

        Light Containment (north) -> Heavy Containment -> Entrance Zone (south)

    narrow 2-tile hallways, keycard checkpoints between the zones, and the
    Gate A lift (a cabin in a shaft) up to a fortified compound on the
    surface: access road, two-storey concrete wall, entrance court with a
    watchtower, inner gate, main building over the lift. The levels above
    the surface (roofs, wall tops, the tower) are in D.upper.

    The site is placed by the end of its access road: the admin clicks where
    the road should meet the town road (or sets the FacilityX / FacilityY
    sandbox options), and the compound and the site extend north of it.

    Every function here takes world coordinates.
]]

require "SCP_System"
require "SCP_Facility_Data"

SCP.Facility = SCP.Facility or {}
local F = SCP.Facility
local D = F.Data

F.VERSION = 3      -- sites built by an older version are ignored (they keep their old tiles)

F.Zones = {
    L = { id = "LCZ" }, H = { id = "HCZ" }, E = { id = "EZ" },
    SITE = { id = "SITE" }, SURFACE = { id = "SURFACE" },
}

-- Footprint of the site in tiles.
function F.footprint()
    return D.width, D.height
end

-- World position of the site's north-west corner: { x, y, z, v }.
-- z is the underground level. nil when no (current) site exists.
function F.origin()
    local md = ModData.get("SCPFoundation")
    local f = md and md.facility
    if f and f.x then
        if f.v == F.VERSION then return f end
        return nil
    end
    local x, y = SCP.opt("FacilityX"), SCP.opt("FacilityY")
    if x and y and x > 0 and y > 0 then
        return F.originForGate(x, y)
    end
    return nil
end

-- Origin of a site whose access road ends at (gateX, gateY).
function F.originForGate(gateX, gateY)
    return { x = gateX - D.anchor.x, y = gateY - D.anchor.y, z = SCP.opt("FacilityDepth"), v = F.VERSION }
end

-- Tile of the plan under a world position, or nil outside the footprint.
function F.toLocal(x, y)
    local o = F.origin()
    if not o then return nil end
    local lx, ly = math.floor(x) - o.x, math.floor(y) - o.y
    if lx < 0 or ly < 0 or lx >= D.width or ly >= D.height then return nil end
    return lx, ly, o
end

-- Character of a layer ("floor", "west", "north", "zone") at a plan tile.
function F.charAt(level, layer, lx, ly)
    local rows = level[layer]
    local row = rows and rows[ly + 1]
    if not row or lx < 0 or lx >= #row then return " " end
    return row:sub(lx + 1, lx + 1)
end

-- The plan level a world z belongs to: D.underground, D.surface or nil.
function F.planLevel(z, o)
    z = math.floor(z)
    if z == o.z then return D.underground end
    if z == 0 then return D.surface end
    return nil
end

-- Which zone of the site a position is in ({ id = "LCZ" | "HCZ" | "EZ" | "SITE" }),
-- or nil outside the underground site. Used as "is this inside the site?".
function F.levelAt(x, y, z)
    local lx, ly, o = F.toLocal(x, y)
    if not lx or math.floor(z) ~= o.z then return nil end
    for _, d in ipairs({ { 0, 0 }, { 1, 0 }, { -1, 0 }, { 0, 1 }, { 0, -1 } }) do
        local zone = F.Zones[F.charAt(D.underground, "zone", lx + d[1], ly + d[2])]
        if zone then return zone end
    end
    return F.Zones.SITE
end

-- The room at a position: its kind ("scp008", "lab", ...), the zone, the room itself.
function F.roomAt(x, y, z)
    local lx, ly, o = F.toLocal(x, y)
    if not lx then return nil end
    local level = F.planLevel(z, o)
    if not level then return nil end
    for _, r in ipairs(level.rooms) do
        if lx >= r.x0 and lx <= r.x1 and ly >= r.y0 and ly <= r.y1 then
            return r.kind, F.levelAt(x, y, z), r
        end
    end
    return nil, F.levelAt(x, y, z)
end

-- World position of the centre of the first room of a kind in a zone (for spawns).
function F.roomCenter(zoneId, kind)
    local o = F.origin()
    if not o then return nil end
    for _, level in ipairs({ D.underground, D.surface }) do
        for _, r in ipairs(level.rooms) do
            if r.kind == kind and (zoneId == nil or r.zone == zoneId) then
                return o.x + r.cx, o.y + r.cy, level == D.surface and 0 or o.z
            end
        end
    end
    return nil
end

-- Tesla gates
local teslaTiles = nil
function F.isTesla(x, y, z)
    local lx, ly, o = F.toLocal(x, y)
    if not lx or math.floor(z) ~= o.z then return false end
    if not teslaTiles then
        teslaTiles = {}
        for _, t in ipairs(D.underground.tesla) do teslaTiles[t.x .. "," .. t.y] = true end
    end
    return teslaTiles[lx .. "," .. ly] == true
end

-- Where a lift goes: the matching platform on the other level.
-- Returns { label, x, y, z } entries (world coordinates).
function F.liftDestinations(info)
    local o = F.origin()
    if not o or not info then return {} end
    local toSurface = info.level ~= "SURFACE"
    local level = toSurface and D.surface or D.underground
    for _, l in ipairs(level.lifts) do
        if l.link == info.link then
            return { { label = toSurface and "SURFACE" or "EZ", x = o.x + l.x, y = o.y + l.y, z = toSurface and 0 or o.z } }
        end
    end
    return {}
end
